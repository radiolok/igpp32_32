#!/usr/bin/env python3
"""Extract frameBuffer[2][1152] from the MSP430 firmware into a C++ source.

Usage: extract_msp_frames.py fw/igpp32-32/Igpp.c fw-esp32/components/igpp_core/src/msp_picture.cpp
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
body = src[src.index("frameBuffer"):]
body = body[body.index("{"):]
depth, end = 0, 0
for i, ch in enumerate(body):
    depth += ch == "{"
    depth -= ch == "}"
    if depth == 0:
        end = i
        break
values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body[:end])]
assert len(values) == 2 * 1152, len(values)

lines = ["// Generated by tools/extract_msp_frames.py from fw/igpp32-32/Igpp.c. Do not edit.",
         '#include "igpp/patterns.hpp"', "", "namespace igpp::patterns {", "",
         "const uint8_t kMspPicture[2][kFrameBytes] = {"]
for f in range(2):
    lines.append("    {")
    chunk = values[f * 1152:(f + 1) * 1152]
    for i in range(0, 1152, 12):
        lines.append("        " + ", ".join(f"0x{v:02X}" for v in chunk[i:i + 12]) + ",")
    lines.append("    },")
lines += ["};", "", "}  // namespace igpp::patterns", ""]
open(sys.argv[2], "w").write("\n".join(lines))
